export type MachineName = keyof typeof MACHINES;

export class InvalidTransitionError extends Error {
  constructor(
    public readonly machine: string,
    public readonly from: string,
    public readonly to: string,
  ) {
    super(`Invalid ${machine} transition ${from} → ${to}`);
  }
}

export function canTransition(machine: MachineName, from: string, to: string): boolean {
  const map = MACHINES[machine] as Record<string, readonly string[]>;
  return (map[from] ?? []).includes(to);
}

export function assertTransition(machine: MachineName, from: string, to: string): void {
  if (!canTransition(machine, from, to)) throw new InvalidTransitionError(machine, from, to);
}

/** Index of a state in the canonical application order (for "has reached" comparisons). */
export function applicationStageIndex(state: ApplicationState): number {
  return APPLICATION_STATES.indexOf(state);
}

export function hasReached(current: ApplicationState, target: ApplicationState): boolean {
  if (TERMINAL_APPLICATION_STATES.includes(current) && current !== 'COMPLETED') return false;
  if (current === 'EXCEPTION') return false;
  return applicationStageIndex(current) >= applicationStageIndex(target);
}
